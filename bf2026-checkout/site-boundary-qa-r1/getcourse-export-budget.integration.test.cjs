'use strict';
const {test}=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const enabled=process.env.BF2026_STAGE_ONLY==='1'&&Boolean(process.env.BF2026_STAGE_PG_POOL_MODULE);
const {createPostgresBudget}=require('./getcourse-export-readback.cjs');
test('R122 actual PostgreSQL export budget serializes one outstanding export and cleans up',{skip:!enabled},async t=>{
 const pool=require(process.env.BF2026_STAGE_PG_POOL_MODULE).pool;
 assert.equal(pool.options.host,'127.0.0.1');
 assert.equal(Number(pool.options.port),55439);
 assert.equal(pool.options.database,'bfstage');
 await pool.query(fs.readFileSync(path.join(__dirname,'getcourse-export-budget.sql'),'utf8'));
 const host='study.shkola-dnv.com';
 const before=await pool.query('SELECT request_count,outstanding_export_id FROM bf2026_getcourse_export_budget WHERE account_host=$1',[host]);
 assert.equal(before.rowCount,1);
 assert.equal(before.rows[0].outstanding_export_id,null,'do not disturb an existing export lease');
 assert.equal(Number(before.rows[0].request_count),0,'do not consume a live export budget');
 const budget=createPostgresBudget(pool);
 t.after(async()=>{
  await pool.query("UPDATE bf2026_getcourse_export_budget SET request_count=0,window_started_at=now(),outstanding_export_id=NULL,outstanding_since=NULL,updated_at=now() WHERE account_host=$1",[host]);
  await pool.end();
 });
 await budget.claimStart();
 let row=await pool.query('SELECT request_count,outstanding_export_id FROM bf2026_getcourse_export_budget WHERE account_host=$1',[host]);
 assert.equal(Number(row.rows[0].request_count),1);
 assert.equal(row.rows[0].outstanding_export_id,'CREATING');
 await assert.rejects(budget.claimStart(),{code:'GETCOURSE_EXPORT_ALREADY_IN_PROGRESS'});
 await budget.markExport('r122_stage_export_1');
 await assert.rejects(budget.claimPoll('wrong_export'),{code:'GETCOURSE_EXPORT_LEASE_MISMATCH'});
 await budget.claimPoll('r122_stage_export_1');
 row=await pool.query('SELECT request_count,outstanding_export_id FROM bf2026_getcourse_export_budget WHERE account_host=$1',[host]);
 assert.equal(Number(row.rows[0].request_count),2);
 assert.equal(row.rows[0].outstanding_export_id,'r122_stage_export_1');
 await budget.complete('r122_stage_export_1');
 row=await pool.query('SELECT request_count,outstanding_export_id FROM bf2026_getcourse_export_budget WHERE account_host=$1',[host]);
 assert.equal(Number(row.rows[0].request_count),2);
 assert.equal(row.rows[0].outstanding_export_id,null);
});
